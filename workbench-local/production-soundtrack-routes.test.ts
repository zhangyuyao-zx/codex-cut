import {mkdtemp,rm,writeFile,chmod} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import express from 'express';
import request from 'supertest';
import {it,expect,vi} from 'vitest';
const fixture=vi.hoisted(()=>({cut:null as any}));
vi.mock('./roughcut-service',async importOriginal=>({...await importOriginal<any>(),createRoughcutService:async()=>({get:async()=>structuredClone(fixture.cut),verifyPreview:async()=>{}})}));
vi.mock('./render-runtime-identity',()=>({renderRuntimeIdentity:async()=> 'runtime-test'}));
vi.mock('./scene-media-dependencies',()=>({buildSceneCutIdentity:vi.fn(async()=>({scope:'window',hash:'test-cut-window'}))}));
import {productionRoutes} from './production-routes';
import {createProductionStore} from './production-store';
import {createEditorSelection} from './editor-selection';
import {SegmentReviewStore} from './segment-reviews';
import {buildSceneCutIdentity} from './scene-media-dependencies';
import {runtimeCommand} from './runtime-paths';
const exec=promisify(execFile);
for(const precise of [false,true])it(`soundtrack API protects revisions/drafts and invalidates ${precise?'precise':'fallback'} keys and approvals`,async()=>{
  const project=await mkdtemp(path.join(tmpdir(),'soundtrack-api-'));
  let routes:Awaited<ReturnType<typeof productionRoutes>>|undefined;
  try{
    const words=[{id:'a',text:'开始',startMs:0,endMs:500},{id:'b',text:'结尾',startMs:500,endMs:1000}];
    fixture.cut={revision:3,asset:{url:'/cut-media/source.mp4',name:'fixture',durationMs:1000},words,ranges:[{startMs:0,endMs:1000}],busy:false,preview:{url:'/cut-media/preview.mp4',revision:3}};
    if(precise){fixture.cut.timeline={schemaVersion:1,assets:[{id:'asset',name:'fixture',durationFrames:30,sourceFileName:'source.mp4',proxyFileName:'proxy.mp4',words}],clips:[{id:'clip',assetId:'asset',inFrame:0,outFrame:30,legacyWordIds:true}]};fixture.cut.preview.provenance={renderSource:{url:'/cut-media/render.mkv',contentHash:'a'.repeat(64)},encodingHash:'encoding'};}
    const store=await createProductionStore(path.join(project,'production'));
    await store.setScenes(0,{assetUrl:fixture.cut.asset.url,cutRevision:3},[{id:'scene',title:'Test',intent:'Test',startWordId:'a',endWordId:'b',beats:[],program:{moduleId:'editable-title',parameters:{}}}]);
    routes=await productionRoutes(process.cwd(),project,{detail:vi.fn()} as any);
    const app=express();app.use(express.json());app.use('/api/production',routes);app.use((error:Error,_req:express.Request,res:express.Response,_next:express.NextFunction)=>res.status(409).json({error:error.message}));
    const get=async()=>(await request(app).get('/api/production')).body;
    const post=(data:any)=>request(app).post('/api/production/soundtrack').send(data);
    vi.mocked(buildSceneCutIdentity).mockClear();
    const original=await get();expect(original.programError).toBe('');expect(original.soundtrackStatus).toEqual({mode:'source',ready:true});
    expect(vi.mocked(buildSceneCutIdentity).mock.calls.length>0).toBe(precise);
    const ledger=new SegmentReviewStore(path.join(project,'production/segment-reviews.json'));
    await ledger.save({id:'synthetic-fixture',sceneId:'scene',key:original.segmentReviews[0].key,from:0,end:30,status:'done',revision:1,progress:1,pendingMaterials:false,url:'/production-media/renders/11111111-1111-1111-1111-111111111111/review.mp4',pictureHash:'0'.repeat(64)});
    await ledger.approve('scene','synthetic-fixture',original.segmentReviews[0].key);
    expect((await get()).assemblyReady).toBe(true);
    const input=path.join(project,'master.wav');await exec(runtimeCommand('ffmpeg'),['-v','error','-f','lavfi','-i','sine=frequency=330:duration=1',input]);
    const body={path:input,expectedRevision:1,expectedCutRevision:3};
    expect((await post({...body,expectedCutRevision:2})).status).toBe(409);
    expect((await post({...body,contentHash:'fake'})).status).toBe(409);
    const selection=await createEditorSelection(path.join(project,'production'));
    await selection.set({sceneId:'scene',objectId:null,timeSeconds:0,view:'scene',baseRevision:1,hasUnsavedChanges:true});
    expect((await post(body)).body.error).toContain('未保存');
    await selection.set({sceneId:'scene',objectId:null,timeSeconds:0,view:'scene',baseRevision:1,hasUnsavedChanges:false});
    const bound=await post(body);expect(bound.status).toBe(200);expect(bound.body.soundtrackStatus).toMatchObject({mode:'master',ready:true});
    expect(bound.body.segmentReviews[0].key).not.toBe(original.segmentReviews[0].key);expect(bound.body.assemblyReady).toBe(false);
    expect(bound.body.props.audioSrc).toContain('/api/production/soundtrack/file/');expect(bound.body.props.scenePrograms[0].audioSrc).toBe(bound.body.props.audioSrc);
    expect((await request(app).get(bound.body.soundtrackStatus.url)).status).toBe(200);
    expect((await post(body)).status).toBe(409);
    fixture.cut.revision=4;
    const stale=await get();expect(stale.programError).toContain('完整混音');expect(stale.soundtrackStatus.ready).toBe(false);expect(stale.assemblyReady).toBe(false);
    fixture.cut.revision=3;
    const stored=path.join(project,'production/soundtracks',bound.body.plan.soundtrack.fileName);
    await chmod(stored,0o644);await writeFile(stored,'replacement');
    const changed=await get();expect(changed.programError).toContain('丢失或变化');expect(changed.segmentReviews[0].key).not.toBe(bound.body.segmentReviews[0].key);expect(changed.props).toBe(null);
    expect((await request(app).get(bound.body.soundtrackStatus.url)).status).toBe(409);
    const cleared=await post({path:null,expectedRevision:2,expectedCutRevision:3});expect(cleared.status).toBe(200);expect(cleared.body.plan).toMatchObject({soundtrack:null,soundtrackRevision:2});
    expect(cleared.body.soundtrackStatus).toEqual({mode:'source',ready:true});expect(cleared.body.programError).toBe('');expect(cleared.body.segmentReviews[0].key).not.toBe(original.segmentReviews[0].key);expect(cleared.body.assemblyReady).toBe(false);
  }finally{await routes?.shutdown();await rm(project,{recursive:true,force:true});}
});
